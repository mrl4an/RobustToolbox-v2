using System;
using System.Collections.Generic;
using System.Linq;
using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.Placement;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Graphics;
using Robust.Shared.IoC;
using Robust.Shared.Localization;
using Robust.Shared.Maths;
using Robust.Shared.Prototypes;

namespace Robust.Client.UserInterface.CustomControls
{
    [GenerateTypedNameReferences]
    public sealed partial class EntitySpawnWindow : DefaultWindow
    {
        private static readonly LocId NoDescriptionMessage = "entity-spawn-window-no-description";

        [Dependency] private readonly ILocalizationManager _loc = default!;
        [Dependency] private readonly IPlacementManager _placement = default!;

        public EntitySpawnButton? SelectedButton;
        public EntityPrototype? SelectedPrototype;

        [Obsolete("Use IPlacementManager.AllModeNames")]
        public static string[] InitOpts =>IoCManager.Resolve<IPlacementManager>().AllModeNames;
        public EntitySpawnWindow()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);

            MeasureButton.Measure(Vector2Helpers.Infinity);

            var modes = _placement.AllModeNames;
            for (var i = 0; i < modes.Length; i++)
            {
                OverrideMenu.AddItem(modes[i], i);
            }
        }

        // Create a spawn button and insert it into the start or end of the list.
        /// <summary>
        /// Builds a list entry for an entity prototype and adds it to the prototype list.
        /// </summary>
        /// <param name="prototype">The prototype the entry represents.</param>
        /// <param name="insertFirst">If true the entry is moved to the top of the list; otherwise it stays at the end.</param>
        /// <param name="index">Position of the prototype in the source ordering. Only kept for debugging.</param>
        /// <returns>The newly created entry.</returns>
        public EntitySpawnButton InsertEntityButton(EntityPrototype prototype, bool insertFirst, int index)
        {
            var button = new EntitySpawnButton
            {
                Prototype = prototype,
                Index = index
            };

            // Display name falls back to the prototype id; an optional editor suffix is shown in brackets.
            var label = string.IsNullOrEmpty(prototype.Name) ? prototype.ID : prototype.Name;
            if (!string.IsNullOrWhiteSpace(prototype.EditorSuffix))
            {
                label += " [" + prototype.EditorSuffix + "]";
            }

            button.EntityLabel.Text = label;

            var description = string.IsNullOrEmpty(prototype.Description)
                ? _loc.GetString(NoDescriptionMessage)
                : prototype.Description;
            button.ActualButton.ToolTip = prototype.ID + "\n" + description;

            // Keep the current selection highlighted when the list is rebuilt.
            if (prototype == SelectedPrototype)
            {
                SelectedButton = button;
                button.ActualButton.Pressed = true;
            }

            button.EntityTextureRects.SetPrototype(prototype.ID);

            PrototypeList.AddChild(button);
            if (insertFirst)
            {
                button.SetPositionInParent(0);
            }

            return button;
        }
    }
}
